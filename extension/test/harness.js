    await seed({ id: 'rv1', title: 'Vector survival document', body: 'A document about vector survival across index compaction.', summary: 'Vector survival.' });
    await seed({ id: 'rv2', title: 'Second document', body: 'Another document so compaction has something to keep.', summary: 'Second.' });
