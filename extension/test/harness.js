// ---------- tiny test framework ----------

const suites = [];
let current = null;

function describe(name, fn) {
  current = { name, cases: [] };
  suites.push(current);
  fn();
  current = null;
}
function it(name, fn) { current.cases.push({ name, fn }); }

class Skip extends Error {}
function skip(why) { throw new Skip(why); }

function assert(cond, msg) {
  if (!cond) throw new Error(msg || 'assertion failed');
}
function eq(a, b, msg) {
  if (a !== b) throw new Error(`${msg || 'expected equal'}\n  actual:   ${fmt(a)}\n  expected: ${fmt(b)}`);
}
function close(a, b, tol, msg) {
  if (Math.abs(a - b) > tol) throw new Error(`${msg || 'expected close'}\n  actual:   ${a}\n  expected: ${b} ±${tol}`);
}
function gt(a, b, msg) {
  if (!(a > b)) throw new Error(`${msg || 'expected greater'}\n  ${fmt(a)} is not > ${fmt(b)}`);
}
function fmt(v) {
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : v.toFixed(6);
  if (typeof v === 'string') return JSON.stringify(v.length > 120 ? v.slice(0, 120) + '…' : v);
  return String(v);
}

// ---------- fixtures ----------

const LOCAL_SPACE = local.LOCAL_SPACE;

/** Reset both the database and the in-memory index between suites. */
async function freshDb() {
  await store.ready();
  await store.clear();
  index._reset();
  await store.metaSet('index', null);
  ai.clearEmbedCache();
  search.invalidateAnswerCache();
}

async function useLocalProvider() {
  await ai.switchProvider('local');
}

/**
 * Seed a document the way ingest does, but without the summarizer — used by
 * tests that care about retrieval rather than about ingest itself.
 */
async function seed({ id, title, body, summary, createdAt = Date.now(), sourceKind = 'web', tags = [], extra = null, chunked = true }) {
  const chunks = chunked && body.length > 1600
    ? text.chunkText(body)
    : [{ text: body, start: 0, i: 0 }];

  const docText = [title, summary || '', tags.join(', '), body.slice(0, 2000)].filter(Boolean).join('\n\n');
  const docVec = local.embed(docText);
  const chunkRecords = chunks.map((c) => ({
    text: c.text,
    start: c.start,
    vec: local.embed(`${title}\n\n${c.text}`),
  }));

  const memory = {
    id, url: `https://example.test/${id}`, title,
    summary: summary || title, text: body, tags, keyFacts: [],
    contentType: 'article', sourceKind, sourceLabel: '', siteName: 'example.test',
    createdAt, updatedAt: createdAt, embedSpace: LOCAL_SPACE,
    chunkCount: chunkRecords.length, excerpt: '', selection: '',
    favicon: '', author: '', publishedAt: '', mime: '', extra,
    ...(summary ? {} : { lightweight: true }),
  };
  await store.put(memory);
  await index.addDoc({
    id, vec: docVec, space: LOCAL_SPACE, createdAt,
    chunks: chunkRecords,
    tokensText: [title, summary || '', tags.join(' '), body].filter(Boolean).join('\n'),
  });
  return memory;
}

/** Filler prose with none of the marker vocabulary, to pad long documents. */
function filler(paragraphs, seedWord = 'general') {
  const sentences = [
    `The ${seedWord} overview begins with background material that sets out the ordinary situation.`,
    `Standard procedure covers the usual arrangements without departing from established practice.`,
    `Routine observations were collected and tabulated in the customary manner throughout.`,
    `Nothing in this passage departs from the conventional treatment of the ordinary subject.`,
    `Further discussion continues along familiar lines with additional supporting commentary.`,
  ];
  const out = [];
  for (let i = 0; i < paragraphs; i++) {
    out.push(sentences.map((s) => s.replace('§', String(i))).join(' '));
  }
  return out.join('\n\n');
}

// ================= vector maths =================

describe('Vector maths', () => {
  it('normalize produces a unit vector', () => {
    const v = vec.normalize([3, 4, 0, 0]);
    close(Math.sqrt(v.reduce((s, x) => s + x * x, 0)), 1, 1e-6, 'length should be 1');
    close(v[0], 0.6, 1e-6);
    close(v[1], 0.8, 1e-6);
  });

  it('normalize leaves a zero vector alone instead of dividing by zero', () => {
    const v = vec.normalize([0, 0, 0]);
    assert(v.every((x) => x === 0), 'should stay zero');
    assert(!v.some(Number.isNaN), 'must not produce NaN');
  });

  it('dot of a unit vector with itself is 1', () => {
    const v = vec.normalize([0.2, -0.7, 0.4, 0.1, 0.9]);
    close(vec.dot(v, v), 1, 1e-6);
  });

  it('quantisation round-trips within half a step', () => {
    const v = vec.normalize(Array.from({ length: 256 }, (_, i) => Math.sin(i * 0.37)));
    const { q, scale } = vec.quantize(v);
    const back = vec.dequantize(q, scale);
    let maxErr = 0;
    for (let i = 0; i < v.length; i++) maxErr = Math.max(maxErr, Math.abs(v[i] - back[i]));
    // The step size is the per-vector scale, so half of it is the worst case.
    assert(maxErr <= scale * 0.5 + 1e-9, `max component error ${maxErr} exceeds half a step (${scale * 0.5})`);
    return `step ${scale.toExponential(3)}, worst component error ${maxErr.toExponential(3)}`;
  });

  it('quantising a zero vector yields a zero scale rather than NaN', () => {
    const { q, scale } = vec.quantize(new Float32Array(16));
    eq(scale, 0);
    assert(q.every((x) => x === 0));
    const back = vec.dequantize(q, scale);
    assert(back.every((x) => x === 0), 'dequantising must not produce NaN');
  });

  it('quantised similarity tracks exact similarity at full 1536 width', () => {
    // At mem's real width the components of a unit vector are tiny, which is
    // exactly where a fixed quantisation scale falls apart. This asserts the
    // per-vector scale is doing its job.
    const a = vec.normalize(Array.from({ length: 1536 }, (_, i) => Math.sin(i * 0.11)));
    const b = vec.normalize(Array.from({ length: 1536 }, (_, i) => Math.sin(i * 0.11 + 0.3)));
    const exact = vec.dot(a, b);
    const qa = vec.quantize(a);
    const qb = vec.quantize(b);
    const approx = vec.dot(vec.dequantize(qa.q, qa.scale), vec.dequantize(qb.q, qb.scale));
    close(approx, exact, 0.005, 'quantised similarity should stay within 0.005 of exact');
    return `exact ${exact.toFixed(6)} vs quantised ${approx.toFixed(6)} (error ${Math.abs(approx - exact).toFixed(6)})`;
  });

  it('the per-vector scale beats a fixed scale at high dimension', () => {
    const a = vec.normalize(Array.from({ length: 1536 }, (_, i) => Math.sin(i * 0.11)));
    const b = vec.normalize(Array.from({ length: 1536 }, (_, i) => Math.sin(i * 0.11 + 0.3)));
    const exact = vec.dot(a, b);

    const qa = vec.quantize(a);
    const qb = vec.quantize(b);
    const perVector = Math.abs(vec.dot(vec.dequantize(qa.q, qa.scale), vec.dequantize(qb.q, qb.scale)) - exact);

    // Reproduce the old fixed-scale behaviour for comparison.
    const fixed = (v) => {
      const out = new Float32Array(v.length);
      for (let i = 0; i < v.length; i++) {
        out[i] = Math.max(-127, Math.min(127, Math.round(v[i] * 127))) / 127;
      }
      return out;
    };
    const fixedErr = Math.abs(vec.dot(fixed(a), fixed(b)) - exact);
    gt(fixedErr, perVector, 'the per-vector scale should be more accurate');
    return `error: per-vector ${perVector.toFixed(6)}, fixed scale ${fixedErr.toFixed(6)} (${(fixedErr / Math.max(perVector, 1e-9)).toFixed(0)}× worse)`;
  });

  it('scanPacked agrees with a direct dot product', () => {
    const dim = 64;
    const rows = 10;
    const matrix = new Int8Array(rows * dim);
    const scales = new Float32Array(rows);
    const vecs = [];
    for (let r = 0; r < rows; r++) {
      const v = vec.normalize(Array.from({ length: dim }, (_, i) => Math.sin(i * (r + 1) * 0.13)));
      vecs.push(v);
      const { q, scale } = vec.quantize(v);
      matrix.set(q, r * dim);
      scales[r] = scale;
    }
    const qv = vec.quantize(vecs[3]);
    const scores = vec.scanPacked(qv.q, qv.scale, matrix, scales, dim, rows);
    let best = 0;
    for (let r = 1; r < rows; r++) if (scores[r] > scores[best]) best = r;
    eq(best, 3, 'the query vector should match its own row');
    close(scores[3], 1, 0.01, 'self-similarity should be ~1');
    // Every row should track its exact counterpart.
    for (let r = 0; r < rows; r++) {
      close(scores[r], vec.dot(vecs[3], vecs[r]), 0.01, `row ${r} should match the exact dot product`);
    }
  });

  it('topK returns the k highest scores in order', () => {
    const scores = Float32Array.from([0.1, 0.9, 0.5, 0.7, 0.2, 0.95, 0.3]);
    const top = vec.topK(scores, 3);
    eq(top.length, 3);
    eq(top[0].i, 5);
    eq(top[1].i, 1);
    eq(top[2].i, 3);
  });

  it('topK honours the allow filter', () => {
    const scores = Float32Array.from([0.9, 0.8, 0.7, 0.6]);
    const top = vec.topK(scores, 2, (i) => i !== 0);
    eq(top[0].i, 1);
    eq(top[1].i, 2);
  });

  it('RRF rewards appearing in both lists over topping just one', () => {
    // This is the property that matters for hybrid retrieval: a document
    // both arms agree on beats one that only a single arm ranked first.
    const fused = vec.rrf([
      { name: 'vector', ids: ['a', 'b'] },
      { name: 'lexical', ids: ['b', 'c'] },
    ]);
    eq(fused[0].id, 'b', 'the document both arms found should win');
    assert(fused[0].ranks.vector === 2 && fused[0].ranks.lexical === 1,
      'the winner should carry its rank in each list');
  });

  it('RRF needs no score normalisation to combine unlike scales', () => {
    // BM25 scores are unbounded and cosine scores sit in [-1, 1]. RRF only
    // reads rank position, so the scales never have to be reconciled.
    const fused = vec.rrf([
      { name: 'lexical', ids: ['big', 'small'] },   // scores might be 40.2, 38.9
      { name: 'vector', ids: ['small', 'big'] },    // scores might be 0.81, 0.79
    ]);
    eq(fused.length, 2);
    close(fused[0].score, fused[1].score, 1e-3, 'a symmetric disagreement should be near-tied');
  });

  it('RRF weights shift the outcome', () => {
    const even = vec.rrf([
      { name: 'x', ids: ['a', 'z'], weight: 1 },
      { name: 'y', ids: ['z', 'a'], weight: 1 },
    ]);
    eq(even[0].id, 'a', 'ties break toward the first list');
    const weighted = vec.rrf([
      { name: 'x', ids: ['a', 'z'], weight: 0.2 },
      { name: 'y', ids: ['z', 'a'], weight: 1 },
    ]);
    eq(weighted[0].id, 'z', 'the heavier list should decide');
  });

  it('MMR drops near-duplicates in favour of something different', () => {
    const dup = vec.normalize([1, 0, 0, 0]);
    const dup2 = vec.normalize([0.99, 0.01, 0, 0]);
    const dup3 = vec.normalize([0.98, 0.02, 0, 0]);
    const other = vec.normalize([0, 1, 0, 0]);
    // Scores close together, as fused RRF scores in a real candidate set are.
    const picked = vec.mmr([
      { id: 'a', score: 1.00, vec: dup },
      { id: 'b', score: 0.98, vec: dup2 },
      { id: 'c', score: 0.97, vec: dup3 },
      { id: 'd', score: 0.85, vec: other },
    ], { lambda: 0.7, k: 2 });
    eq(picked[0].id, 'a', 'the most relevant item leads');
    eq(picked[1].id, 'd', 'the second slot should go to the distinct item, not a duplicate');
  });

  it('MMR still respects relevance when nothing is redundant', () => {
    const orthogonal = (i) => {
      const v = new Float32Array(4);
      v[i] = 1;
      return v;
    };
    const picked = vec.mmr([
      { id: 'a', score: 1.0, vec: orthogonal(0) },
      { id: 'b', score: 0.9, vec: orthogonal(1) },
      { id: 'c', score: 0.8, vec: orthogonal(2) },
    ], { lambda: 0.7, k: 3 });
    eq(picked.map((p) => p.id).join(','), 'a,b,c', 'with no redundancy, order should follow relevance');
  });

  it('MMR does not divide by zero when every score is zero', () => {
    const picked = vec.mmr([
      { id: 'a', score: 0, vec: vec.normalize([1, 0]) },
      { id: 'b', score: 0, vec: vec.normalize([0, 1]) },
    ], { lambda: 0.7, k: 2 });
    eq(picked.length, 2);
    assert(picked.every((p) => p.id), 'should still return both items');
  });
});

// ================= chunking =================

describe('Chunking', () => {
  it('covers every character of the document', () => {
    const doc = filler(60, 'coverage');
    const chunks = text.chunkText(doc);
    gt(chunks.length, 1, 'a long document should produce several chunks');
    // Walk the chunks and confirm the union is the whole range.
    let reach = 0;
    for (const c of chunks) {
      assert(c.start <= reach, `gap in coverage before offset ${c.start} (reached ${reach})`);
      reach = Math.max(reach, c.end);
    }
    eq(reach, doc.length, 'coverage must extend to the final character');
    eq(chunks[0].start, 0, 'coverage must start at zero');
    return `${chunks.length} chunks over ${doc.length} chars`;
  });

  it('chunk text matches the source slice exactly', () => {
    const doc = filler(40, 'slices');
    for (const c of text.chunkText(doc)) {
      eq(c.text, doc.slice(c.start, c.end), `chunk ${c.i} text should equal its slice`);
    }
  });

  it('respects the size ceiling', () => {
    const doc = filler(80, 'ceiling');
    for (const c of text.chunkText(doc, { target: 800, max: 1200 })) {
      assert(c.end - c.start <= 1200, `chunk ${c.i} is ${c.end - c.start} chars, over the 1200 ceiling`);
    }
  });

  it('consecutive chunks overlap so facts on a boundary survive', () => {
    const doc = filler(40, 'overlap');
    const chunks = text.chunkText(doc);
    let overlaps = 0;
    for (let i = 1; i < chunks.length; i++) {
      if (chunks[i].start < chunks[i - 1].end) overlaps++;
    }
    gt(overlaps, 0, 'at least some chunks should overlap');
    return `${overlaps}/${chunks.length - 1} boundaries overlap`;
  });

  it('force-splits a run with no sentence boundaries', () => {
    const wall = 'x'.repeat(9000);
    const chunks = text.chunkText(wall, { target: 1000, max: 1400 });
    gt(chunks.length, 4, 'an unbroken wall of text must still be split');
    for (const c of chunks) assert(c.end - c.start <= 1400, 'force-split chunk over ceiling');
    let reach = 0;
    for (const c of chunks) reach = Math.max(reach, c.end);
    eq(reach, wall.length, 'force-split must still cover everything');
  });

  it('leaves a short document as a single chunk', () => {
    const chunks = text.chunkText('One short paragraph, nothing more.');
    eq(chunks.length, 1);
    eq(chunks[0].start, 0);
  });

  it('handles an empty document without throwing', () => {
    eq(text.chunkText('').length, 0);
  });
});

