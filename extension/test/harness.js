describe('Buried facts in long documents', () => {
  // This is the failure the whole rewrite exists to fix. A long document used
  // to get one embedding computed over its title plus the first 2,000
  // characters, so anything past that point could not be retrieved by meaning
  // no matter how the question was phrased.
  const MARKER = 'The anomalous readings were traced to a miscalibrated thermocouple in bay seven.';
  let doc, buriedAt;

  it('sets up a long document with a distinctive fact near the end', () => {
    const head = filler(30, 'introductory');
    const tail = filler(10, 'closing');
    doc = `${head}\n\n${MARKER}\n\n${tail}`;
    buriedAt = doc.indexOf(MARKER);
    gt(buriedAt, 12000, 'the marker must sit well past any document-level embedding window');
    return `${doc.length} chars, marker at offset ${buriedAt}`;
  });

  it('a document-level embedding alone cannot find the buried fact', () => {
    // Reproduce the old behaviour exactly: embed title + first 2,000 chars.
    const oldStyle = local.embed(`Field report\n\n${doc.slice(0, 2000)}`);
    const query = local.embed('miscalibrated thermocouple bay seven anomalous readings');
    const sim = vec.dot(oldStyle, query);
    assert(sim < 0.2, `old-style embedding scored ${sim.toFixed(4)} — expected near zero`);
    return `document-level similarity to the question: ${sim.toFixed(4)}`;
  });

  it('the chunk containing the fact matches far better than the document does', () => {
    const chunks = text.chunkText(doc);
    const query = local.embed('miscalibrated thermocouple bay seven anomalous readings');
    const docLevel = vec.dot(local.embed(`Field report\n\n${doc.slice(0, 2000)}`), query);

    let best = -1, bestI = -1;
    chunks.forEach((c, i) => {
      const s = vec.dot(local.embed(`Field report\n\n${c.text}`), query);
      if (s > best) { best = s; bestI = i; }
    });

    assert(chunks[bestI].text.includes('thermocouple'),
      'the best-matching chunk should be the one containing the fact');
    // The absolute number depends on the embedder; the ratio is the claim.
    gt(best / Math.max(docLevel, 1e-6), 3,
      `chunk similarity ${best.toFixed(4)} was not meaningfully better than document-level ${docLevel.toFixed(4)}`);
    return `chunk #${bestI} of ${chunks.length}: ${best.toFixed(4)} vs document-level ${docLevel.toFixed(4)} — ${(best / docLevel).toFixed(1)}× better`;
  });

  it('end-to-end retrieval returns the fact as evidence', async () => {
    await freshDb();
    await useLocalProvider();
    await seed({ id: 'long', title: 'Field report', body: doc, summary: 'A long field report covering routine observations.' });
    // Decoys that are plausible neighbours but do not contain the fact.
    await seed({ id: 'decoy1', title: 'Equipment manual', body: filler(20, 'equipment'), summary: 'Equipment handling manual.' });
    await seed({ id: 'decoy2', title: 'Weekly notes', body: filler(20, 'weekly'), summary: 'Notes from the week.' });
    await index.flush();

    const hits = await search.search('miscalibrated thermocouple in bay seven', { limit: 3 });
    gt(hits.length, 0, 'retrieval returned nothing');
    eq(hits[0].memory.id, 'long', 'the long document should rank first');
    assert(hits[0].evidence, 'the hit should carry an evidence passage');
    assert(hits[0].evidence.includes('thermocouple'),
      `evidence should contain the buried fact, got: ${hits[0].evidence.slice(0, 160)}…`);
    return `evidence passage starts at char ${hits[0].evidenceStart} and contains the fact`;
  });

  it('the evidence handed to the model is the matched passage, not the opening', async () => {
    const hits = await search.search('miscalibrated thermocouple in bay seven', { limit: 1 });
    const ctx = ai.formatContext([{ ...hits[0].memory, evidence: hits[0].evidence }]);
    assert(ctx.includes('Matched passage'), 'context should be built from the matched passage');
    assert(ctx.includes('thermocouple'), 'the fact must reach the model');
    assert(!ctx.startsWith('[#1] (just now [web] [title-only]'), 'should not be treated as title-only');
  });
});

