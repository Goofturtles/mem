describe('Index write ownership', () => {
  it('rejects writes when the index is read-only', async () => {
    await freshDb();
    await useLocalProvider();
    await seed({ id: 'ro1', title: 'Before read-only', body: 'A document indexed while writes were still permitted.', summary: 'Before.' });
    await index.flush();

    index.setReadOnly(true);
    try {
      let threw = false;
      try {
        await index.addDoc({ id: 'ro2', vec: null, space: null, createdAt: Date.now(), chunks: [], tokensText: 'should not be written' });
      } catch { threw = true; }
      assert(threw, 'addDoc must throw rather than corrupt the shared ordinal table');

      threw = false;
      try { await index.removeDoc('ro1'); } catch { threw = true; }
      assert(threw, 'removeDoc must throw too');

      // Reads keep working — that is the whole point of read-only.
      const hits = await index.searchLexical('read-only permitted');
      gt(hits.length, 0, 'reads must still work');
    } finally {
      index.setReadOnly(false);
    }
  });

  it('a read-only flush is a no-op rather than an error', async () => {
    index.setReadOnly(true);
    try {
      await index.flush(); // must not throw
    } finally {
      index.setReadOnly(false);
    }
  });
});

