// mem test harness.
//
// Everything here runs with no network and no API key. Two seams make that
// possible, and neither is test-only code inside the product:
//
//   1. local.js resolves Chrome's built-in model lazily, by reading
//      globalThis.LanguageModel at call time. So defining a stub before the
//      first call is enough to exercise the whole on-device path.
//   2. Setting the provider to 'local' routes embeddings through the real
//      hashed embedder, which is pure, deterministic JavaScript. Every
//      similarity number below is reproducible.
//
// Served from localhost this page has its own origin, so its IndexedDB is a
// different database from the installed extension's. Running it cannot touch
// real memories.

// ---------- stub the on-device model (before any module reads it) ----------

globalThis.LanguageModel = {
  async availability() { return 'available'; },
  async create() {
    return {
      async prompt(text) {
        // The summarizer path is the only thing that asks for JSON.
        if (/JSON|summary/i.test(text)) {
          return JSON.stringify({
            summary: 'A stubbed summary produced by the test harness for deterministic runs.',
            tags: ['testing', 'harness', 'retrieval'],
            keyFacts: ['Generated by the harness, not a model.'],
            contentType: 'article',
            entities: [],
          });
        }
        return 'stub answer';
      },
      async *promptStreaming() { yield 'stub answer'; },
      destroy() {},
    };
  },
};

