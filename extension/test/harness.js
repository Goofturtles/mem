describe('Migration from v1', () => {
  it('lifts v1 embeddings into the index without any API call', async () => {
    // Build a genuine v1 database: version 1, embeddings inline on each
    // memory record, no vector/chunk/postings stores.
    store._resetConnection();
    index._reset();
    await new Promise((resolve, reject) => {
      const del = indexedDB.deleteDatabase('mem');
      del.onsuccess = resolve;
      del.onerror = () => reject(del.error);
      del.onblocked = resolve;
    });

    const v1Vec = Array.from(local.embed('legacy memory about tidal turbines and marine energy'));
    await new Promise((resolve, reject) => {
      const req = indexedDB.open('mem', 1);
      req.onupgradeneeded = (e) => {
        const db = e.target.result;
        const s = db.createObjectStore('memories', { keyPath: 'id' });
        s.createIndex('url', 'url', { unique: false });
        s.createIndex('createdAt', 'createdAt', { unique: false });
        s.createIndex('tags', 'tags', { unique: false, multiEntry: true });
      };
      req.onsuccess = () => {
        const db = req.result;
        const t = db.transaction('memories', 'readwrite');
        t.objectStore('memories').put({
          id: 'legacy1',
          url: 'https://example.test/legacy',
          title: 'Tidal turbines',
          summary: 'Legacy memory about tidal turbines and marine energy generation.',
          text: 'Tidal turbines convert marine currents into electricity using submerged rotors.',
          tags: ['tidal', 'marine energy'],
          keyFacts: [],
          embedding: v1Vec,
          createdAt: Date.now() - 86400000,
          updatedAt: Date.now() - 86400000,
          sourceKind: 'web',
        });
        t.oncomplete = () => { db.close(); resolve(); };
        t.onerror = () => reject(t.error);
      };
      req.onerror = () => reject(req.error);
    });

    const result = await store.migrateIfNeeded();
    assert(result.migrated, 'migration should have run');
    eq(result.count, 1, 'one memory should have migrated');

    const m = await store.get('legacy1');
    assert(m, 'the memory should survive migration');
    eq(m.title, 'Tidal turbines');
    assert(!('embedding' in m), 'the inline embedding should have been stripped from the record');

    const rec = await store.getChunks('legacy1');
    assert(rec?.docVec, 'the vector should now live in the chunk store');
    return `migrated ${result.count} memory, vector preserved at ${rec.docVec.length} dims`;
  });

  it('migrated memories are retrievable by both arms', async () => {
    await useLocalProvider();
    // The v1 vector carried no space tag, so it was adopted into the index.
    const lex = await index.searchLexical('tidal turbines');
    gt(lex.length, 0, 'BM25 should find the migrated memory');
    eq(lex[0].id, 'legacy1');

    const sem = await index.searchVectors(local.embed('tidal turbines marine energy'), { k: 3 });
    gt(sem.length, 0, 'the migrated vector should be searchable');
    eq(sem[0].id, 'legacy1');
    return `lexical ${lex[0].score.toFixed(3)}, semantic ${sem[0].score.toFixed(3)}`;
  });

  it('migration is idempotent', async () => {
    const again = await store.migrateIfNeeded();
    assert(!again.migrated, 're-running migration should be a no-op');
    assert(await store.get('legacy1'), 'the memory should still be there');
  });
});

