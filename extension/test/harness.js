// ================= commitment detection =================

describe('Commitment detection', () => {
  // A fixed Wednesday so weekday arithmetic is deterministic.
  const NOW = new Date(2026, 2, 4, 10, 0, 0).getTime(); // Wed 4 Mar 2026, 10:00

  const detect = (t) => commitments.detectCommitment(t, { now: NOW });

  it('resolves a weekday and clock time together', () => {
    const w = commitments.parseWhen("the lab report is due Friday at 3pm", NOW);
    assert(w, 'should parse');
    const d = new Date(w.at);
    eq(d.getDay(), 5, 'should land on Friday');
    eq(d.getHours(), 15, 'should be 3pm');
    eq(d.getDate(), 6, 'should be the coming Friday, 6 March');
  });

  it('a bare weekday means the next one, never today', () => {
    const w = commitments.parseWhen('practice on wednesday', NOW); // NOW is a Wednesday
    const d = new Date(w.at);
    eq(d.getDay(), 3);
    eq(d.getDate(), 11, 'should roll forward a week rather than meaning today');
  });

  it('handles relative offsets', () => {
    eq(commitments.parseWhen('in 30 minutes', NOW).at, NOW + 30 * 60000);
    eq(commitments.parseWhen('in 2 hours', NOW).at, NOW + 2 * 3600000);
    eq(commitments.parseWhen('in 3 days', NOW).at, NOW + 3 * 86400000);
  });

  it('handles tomorrow, tonight, and named dates', () => {
    eq(new Date(commitments.parseWhen('tomorrow at 9am', NOW).at).getDate(), 5);
    eq(new Date(commitments.parseWhen('tonight', NOW).at).getHours(), 20);
    const march = commitments.parseWhen('March 20th', NOW);
    eq(new Date(march.at).getMonth(), 2);
    eq(new Date(march.at).getDate(), 20);
  });

  it('keeps a passed same-day time in the past rather than inventing tomorrow', () => {
    // NOW is 10:00, so "today at 8am" has already gone. "Today" has to keep
    // meaning today, so detection can recognise it as past and stay quiet.
    const w = commitments.parseWhen('today at 8am', NOW);
    eq(new Date(w.at).getDate(), 4, 'should stay on today');
    assert(w.at < NOW, 'should resolve to a past timestamp');
  });

  it('rolls a bare clock time forward to its next occurrence', () => {
    // With no day attached, "at 8" said at 10:00 means the coming 8.
    const w = commitments.parseWhen('call me at 8', NOW);
    assert(w.at > NOW, 'a bare time should resolve into the future');
  });

  it('catches a real chat message with an abbreviation and no cue word', () => {
    // The message that exposed both gaps: "tmrw" wasn't recognised as
    // tomorrow, and neither "hackathon" nor "ending" was a cue, so a genuine
    // deadline produced silence.
    const c = detect('yo i have another hackathon ending tmrw at 12pm im so fried');
    assert(c, 'should detect');
    eq(new Date(c.at).getDate(), 5, 'tmrw should resolve to tomorrow');
    eq(new Date(c.at).getHours(), 12, 'should be 12pm');
    return `"${c.what}" → ${c.whenText} (confidence ${c.confidence.toFixed(2)})`;
  });

  it('understands the abbreviations people actually type', () => {
    for (const [line, dayOfMonth] of [
      ['flight is tmr at 7am', 5],
      ['assignment due tmrw', 5],
      ['see you 2nite', 4],
      ['party tonite at 9pm', 4],
    ]) {
      const w = commitments.parseWhen(line, NOW);
      assert(w, `"${line}" should parse`);
      eq(new Date(w.at).getDate(), dayOfMonth, `"${line}" resolved to the wrong day`);
    }
  });

  it('treats naming a day as evidence in its own right', () => {
    // Requiring a cue word as well meant real messages went unnoticed; no cue
    // list can cover what people actually do with their time.
    const c = detect('the thing is on saturday at 4pm');
    assert(c, 'a named day and time should be enough on its own');
    // But a bare clock with no day still needs a cue, or every mention of a
    // time in conversation would fire.
    assert(!detect('I watched the 3pm showing and it was great'), 'a bare clock still needs a cue');
  });

  it('handles end-of-day and end-of-week deadlines', () => {
    const eod = commitments.parseWhen('essay due eod', NOW);
    eq(new Date(eod.at).getDate(), 4, 'eod is today');
    eq(new Date(eod.at).getHours(), 17, 'eod should mean late afternoon, not midnight');
    const eow = commitments.parseWhen('report due eow', NOW);
    eq(new Date(eow.at).getDay(), 5, 'eow should land on Friday');
  });

  it('fires on a clear obligation with a time', () => {
    const c = detect("don't forget the bio lab report is due Friday at 3pm");
    assert(c, 'should detect a commitment');
    eq(new Date(c.at).getDay(), 5);
    gt(c.confidence, 0.7, 'a deadline with an explicit time should score high');
    return `"${c.what}" → ${c.whenText} (confidence ${c.confidence.toFixed(2)})`;
  });

  it('fires on a rescheduled meeting', () => {
    const c = detect('heads up, the standup moved to tomorrow at 2pm');
    assert(c, 'should detect');
    eq(new Date(c.at).getHours(), 14);
    return `"${c.what}" → ${c.whenText}`;
  });

  it('fires on a direct request with a deadline', () => {
    const c = detect('can you send me the slides by Thursday?');
    assert(c, 'should detect a request with a deadline');
    eq(new Date(c.at).getDay(), 4);
    return `"${c.what}" → ${c.whenText} (confidence ${c.confidence.toFixed(2)})`;
  });

  it('stays silent on a time with no obligation', () => {
    assert(!detect('I watched the 3pm showing and it was great'), 'no obligation cue');
    assert(!detect('the train gets in around 6 usually'), 'no obligation cue');
  });

  it('stays silent on an obligation with no time', () => {
    assert(!detect("don't forget to bring your notes"), 'no time reference');
    assert(!detect('the deadline was last week and we missed it'), 'no parseable future time');
  });

  it('stays silent on hedged plans', () => {
    assert(!detect('maybe we could meet friday?'), 'hedged and questioned');
    assert(!detect('I might go to the game on saturday'), 'hedged');
  });

  it('stays silent on ordinary chatter', () => {
    for (const line of [
      'lol ok', 'the score was 3-2 at halftime', 'https://example.com/meeting-at-3pm',
      'sounds good to me', 'brb', 'that was so funny',
    ]) {
      assert(!detect(line), `should not fire on: ${line}`);
    }
  });

  it('ignores anything already in the past', () => {
    assert(!commitments.detectCommitment('the meeting was at 9am today', { now: NOW }),
      'a passed time is a fact, not a commitment');
  });

  it('strips a chat name prefix from the label', () => {
    const c = detect('Jamie Chen: remember to submit the permission form by Friday');
    assert(c, 'should detect');
    assert(!c.what.startsWith('Jamie Chen:'), `label should drop the speaker prefix, got: ${c.what}`);
    return `label: "${c.what}"`;
  });

  it('describes the countdown in plain language', () => {
    eq(commitments.describeWhen(NOW + 25 * 60000, NOW), 'in 25 min');
    eq(commitments.describeWhen(NOW + 3 * 3600000, NOW), 'in 3 hours');
    eq(commitments.describeWhen(NOW + 26 * 3600000, NOW), 'tomorrow');
    eq(commitments.describeWhen(NOW + 3 * 86400000, NOW), 'in 3 days');
  });

  it('does not fire twice on the same line', () => {
    // Idempotence matters because the observer re-reads the DOM constantly.
    const a = detect('reminder: rehearsal is at 6pm tomorrow');
    const b = detect('reminder: rehearsal is at 6pm tomorrow');
    eq(a.at, b.at, 'the same text must always produce the same timestamp');
    eq(a.what, b.what);
  });
});

// ---------- runner ----------

const resultsEl = document.getElementById('results');
const totalsEl = document.getElementById('totals');
const logEl = document.getElementById('log');
const runBtn = document.getElementById('run');

async function run() {
  runBtn.disabled = true;
  resultsEl.innerHTML = '';
  totalsEl.textContent = '';
  const summary = { pass: 0, fail: 0, skip: 0 };
  const report = [];

  for (const suite of suites) {
    const section = document.createElement('section');
    const h = document.createElement('h2');
    h.textContent = suite.name;
    const count = document.createElement('span');
    count.className = 'count';
    h.appendChild(count);
    section.appendChild(h);
    resultsEl.appendChild(section);

    let localPass = 0;
    for (const c of suite.cases) {
      logEl.textContent = `${suite.name} → ${c.name}`;
      const row = document.createElement('div');
      row.className = 'case';
      const t0 = performance.now();
      let status = 'pass';
      let message = '';
      let detail = '';
      try {
        const out = await c.fn();
        if (typeof out === 'string') detail = out;
        localPass++;
        summary.pass++;
      } catch (e) {
        if (e instanceof Skip) { status = 'skip'; message = e.message; summary.skip++; }
        else { status = 'fail'; message = e.message; summary.fail++; }
      }
      const ms = Math.round(performance.now() - t0);
      row.className = `case ${status}`;
      row.innerHTML = `
        <span class="mark">${status === 'pass' ? '✓' : status === 'fail' ? '✕' : '–'}</span>
        <span class="name"></span>
        <span class="ms">${ms}ms</span>`;
      const nameEl = row.querySelector('.name');
      nameEl.textContent = c.name;
      if (message) {
        const m = document.createElement('div');
        m.className = 'msg';
        m.textContent = message;
        nameEl.appendChild(m);
      }
      if (detail) {
        const d = document.createElement('div');
        d.className = 'detail';
        d.textContent = detail;
        nameEl.appendChild(d);
      }
      section.appendChild(row);
      report.push({ suite: suite.name, name: c.name, status, message, detail, ms });
      // Yield so the page paints between cases.
      await new Promise((r) => setTimeout(r, 0));
    }
    count.textContent = `${localPass}/${suite.cases.length}`;
  }

  logEl.textContent = '';
  totalsEl.innerHTML = `<b>${summary.pass}</b> passed · <b>${summary.fail}</b> failed${summary.skip ? ` · <b>${summary.skip}</b> skipped` : ''}`;
  window.__RESULTS__ = { summary, report };
  window.__DONE__ = true;
  runBtn.disabled = false;
  return summary;
}

runBtn.addEventListener('click', run);
// Auto-run so an automated check just has to load the page and wait.
run();
