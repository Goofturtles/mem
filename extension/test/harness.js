describe('Reminders', () => {
  const remindersMod = () => import('../lib/reminders.js');

  it('rehydrating with an overdue reminder does not deadlock', async () => {
    // Reminder mutations are serialised through one promise chain. Firing an
    // overdue reminder from inside rehydrate — which already holds that lock —
    // waits on a link that only settles when rehydrate returns. The deadlock
    // is silent and total: boot() never resolves, so the periodic alarms are
    // never installed, and because the reminder stays overdue every later
    // wake hangs the same way.
    const rem = await remindersMod();
    const now = Date.now();
    await store.metaSet('reminders', [
      { id: 'od1', what: 'Overdue thing', at: now - 3600000, createdAt: now - 7200000, firedAt: 0, sourceUrl: '', sourceTitle: '', origin: '', snippet: '' },
      { id: 'fut1', what: 'Future thing', at: now + 3600000, createdAt: now, firedAt: 0, sourceUrl: '', sourceTitle: '', origin: '', snippet: '' },
    ]);

    const res = await Promise.race([
      rem.rehydrate(),
      new Promise((r) => setTimeout(() => r({ deadlocked: true }), 5000)),
    ]);
    assert(!res.deadlocked, 'rehydrate() never resolved — the serialisation lock deadlocked');
    eq(res.fired, 1, 'the overdue reminder should have fired');

    const list = await rem.listReminders({ includeFired: true });
    assert(list.find((r) => r.id === 'od1')?.firedAt > 0, 'overdue should be marked fired');
    await store.metaSet('reminders', []);
    return `fired ${res.fired}, chain still responsive`;
  });

  it('the mutation chain still works after firing', async () => {
    const rem = await remindersMod();
    const now = Date.now();
    await store.metaSet('reminders', [
      { id: 'od2', what: 'Another overdue', at: now - 1000, createdAt: now - 2000, firedAt: 0, sourceUrl: '', sourceTitle: '', origin: '', snippet: '' },
    ]);
    await rem.rehydrate();
    const cancelled = await Promise.race([
      rem.cancelReminder('od2').then(() => true),
      new Promise((r) => setTimeout(() => r(false), 4000)),
    ]);
    assert(cancelled, 'a later mutation hung — the chain was left wedged');
    await store.metaSet('reminders', []);
  });
});

// ================= reconciliation =================

describe('Reconciliation', () => {
  it('re-indexes memories that were written but never indexed', async () => {
    // Exactly the state a service worker killed mid-scan leaves behind. It
    // matters because ingest dedupes on record existence, so a re-run would
    // skip these forever.
    await freshDb();
    await useLocalProvider();
    await seed({ id: 'indexed', title: 'Properly indexed document', body: 'A document about tidal turbines that completed its indexing.', summary: 'Indexed.' });
    await index.flush();

    await store.put({
      id: 'orphan', url: 'https://example.test/orphan',
      title: 'Orphaned document about xenobiology',
      summary: 'Written to the store but never indexed, as a killed worker leaves it.',
      text: 'Written to the store but never indexed.',
      tags: [], keyFacts: [], contentType: 'article', sourceKind: 'web',
      siteName: 'example.test', author: '', favicon: '', excerpt: '', selection: '',
      publishedAt: '', mime: '', extra: null, createdAt: Date.now(), updatedAt: Date.now(),
    });

    eq((await index.searchLexical('xenobiology')).length, 0, 'should be unfindable before repair');
    const res = await index.reconcile();
    eq(res.orphans, 1, 'should have found exactly one orphan');
    gt((await index.searchLexical('xenobiology')).length, 0, 'should be findable after repair');
    return `${res.orphans} re-indexed, ${res.stale} stale retired`;
  });

  it('retires ordinals whose record is gone', async () => {
    await freshDb();
    await useLocalProvider();
    await seed({ id: 'keep', title: 'Surviving document', body: 'A document about marine energy that stays put.', summary: 'Survives.' });
    await seed({ id: 'vanish', title: 'Vanishing document', body: 'A document about hydrothermal vents deleted behind the index.', summary: 'Vanishes.' });
    await index.flush();

    // Delete the record without going through remove(), so the index keeps
    // its ordinal — the mirror image of an orphan.
    const db = await store.ready();
    await new Promise((resolve, reject) => {
      const t = db.transaction('memories', 'readwrite');
      t.objectStore('memories').delete('vanish');
      t.oncomplete = resolve;
      t.onerror = () => reject(t.error);
    });

    gt((await index.searchLexical('hydrothermal')).length, 0, 'still scoring before repair');
    const res = await index.reconcile();
    eq(res.stale, 1, 'should have retired one stale ordinal');
    eq((await index.searchLexical('hydrothermal')).length, 0, 'a deleted memory must stop scoring');
    gt((await index.searchLexical('marine energy')).length, 0, 'the survivor is untouched');
  });

  it('is a no-op when the index and store already agree', async () => {
    const res = await index.reconcile();
    eq(res.orphans, 0);
    eq(res.stale, 0);
  });
});

